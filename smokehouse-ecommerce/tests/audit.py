def ok(area, name, cond, info=""):
    R.append((area, name, bool(cond), info))

async def ev(pg, js):
    return await pg.evaluate(js)

async def overflow(pg, area, label):
    w = await ev(pg, "[document.documentElement.scrollWidth, innerWidth]")
    ok(area, f"sem rolagem lateral: {label}", w[0] <= w[1] + 1, f"{w[0]} vs {w[1]}")

async def fresh(ctx, hash="", vp=None):
    pg = await ctx.new_page()
    if vp: await pg.set_viewport_size(vp)
    pg._errs = []
    pg.on("pageerror", lambda e: pg._errs.append("pageerror: " + str(e)))
    pg.on("console", lambda m: m.type == "error" and pg._errs.append("console: " + m.text))
    await pg.goto(URL + hash)
    await pg.wait_for_timeout(300)
    return pg

